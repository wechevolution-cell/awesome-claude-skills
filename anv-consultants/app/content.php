function seed(PDO $pdo): void
{
    $pdo->beginTransaction();
    try {
        $ins = $pdo->prepare('INSERT OR IGNORE INTO settings(key, value) VALUES(?, ?)');
        foreach (default_settings() as $k => $v) {
            $ins->execute([$k, (string) $v]);
        }
        foreach (seed_pages() as $p) {
            insert_seed_page($pdo, $p, null);
        }
        $pdo->commit();
    } catch (\Throwable $e) {
        $pdo->rollBack();
        throw $e;
    }
}

function insert_seed_page(PDO $pdo, array $p, ?int $parentId, string $parentPath = '/'): void
{
    $type = $p['type'];
    $path = $type === 'home' ? '/' : rtrim($parentPath, '/') . '/' . $p['slug'] . '/';
    $body = $p['body'] ?? '';
    $row = [
        'type' => $type,
        'parent_id' => $parentId,
        'slug' => $p['slug'] ?? '',
        'path' => $path,
        'title' => $p['title'],
        'nav_label' => $p['nav'] ?? $p['title'],
        'h1' => $p['h1'] ?? $p['title'],
        'intro' => $p['intro'] ?? '',
        'tldr' => $p['tldr'] ?? '',
        'key_points' => implode("\n", $p['points'] ?? []),
        'body_md' => $body,
        'body_html' => markdown_safe($body),
        'faq_json' => json_encode(array_map(fn($f) => ['q' => $f[0], 'a' => $f[1]], $p['faq'] ?? []), JSON_UNESCAPED_UNICODE),
        'howto_json' => json_encode(array_map(fn($s) => ['name' => $s[0], 'text' => $s[1]], $p['howto'] ?? []), JSON_UNESCAPED_UNICODE),
        'howto_title' => $p['howto_title'] ?? '',
        'sources' => implode("\n", $p['sources'] ?? []),
        'tags' => implode(', ', $p['tags'] ?? []),
        'icon' => $p['icon'] ?? '',
        'meta_title' => $p['meta_title'] ?? '',
        'meta_desc' => $p['meta_desc'] ?? '',
        'focus_kw' => $p['kw'] ?? '',
        'secondary_kws' => implode(', ', $p['kw2'] ?? []),
        'schema_type' => $p['schema'] ?? 'WebPage',
        'noindex' => (int) ($p['noindex'] ?? 0),
        'in_nav' => (int) ($p['in_nav'] ?? 0),
        'sort' => (int) ($p['sort'] ?? 0),
        'status' => 'published',
        'is_placeholder' => 1,
        'author' => '',
        'created_at' => now(),
        'updated_at' => now(),
    ];
    $cols = implode(',', array_keys($row));
    $qs = implode(',', array_fill(0, count($row), '?'));
    $pdo->prepare("INSERT INTO pages($cols) VALUES($qs)")->execute(array_values($row));
    $id = (int) $pdo->lastInsertId();
    foreach ($p['children'] ?? [] as $i => $c) {
        $c['sort'] = $c['sort'] ?? ($i + 1) * 10;
        insert_seed_page($pdo, $c, $id, $path);
    }
}

/** markdown() needs settings for internal-link detection; during seeding settings may be mid-transaction, so guard. */
function markdown_safe(string $md): string
{
    try {
        return markdown($md);
    } catch (\Throwable) {
        return '<p>' . e($md) . '</p>';
    }
}

function sub(string $slug, string $title, string $kw, string $intro, array $points, array $faq, array $sources, array $extra = []): array
{
    $body = "## Τι περιλαμβάνει\n\n" . implode("\n", array_map(fn($p) => '- ' . $p, $points))
        . "\n\n## Πώς ξεκινάμε\n\nΚαλέστε μας ή στείλτε μας email. Θα σας πούμε τι στοιχεία χρειαζόμαστε και πώς προχωράμε για τη δική σας περίπτωση.\n\n> " . PLACEHOLDER_NOTE;
    return array_merge([
        'type' => 'subservice',
        'slug' => $slug,
        'title' => $title,
        'kw' => $kw,
        'intro' => $intro,
        'tldr' => $intro,
        'points' => $points,
        'faq' => $faq,
        'sources' => $sources,
        'body' => $body,
        'schema' => 'Service',
        'meta_desc' => excerpt($intro, 155),
    ], $extra);
}

